SELECT TAPE.APE_ENTIDAD_UMO, TAPE.APE_CENTRO_UMO,
       TC.TCCENTIT, TC.TCCOFICI, TC.TCMOFICI,
       COUNT(*) AS FILAS
FROM GPBT.BGDTAPE TAPE
LEFT JOIN GPBT.TCDT052 TC
       ON TAPE.APE_ENTIDAD_UMO = RIGHT(DIGITS(TC.TCCENTIT), 4)
      AND TAPE.APE_CENTRO_UMO  = RIGHT(DIGITS(TC.TCCOFICI), 4)
WHERE TAPE.APE_PRODUCTO = '02'
  AND TAPE.APE_SUBPRODU IN ('0046', '0047')
  AND TAPE.APE_IND_SITU = 'F'
GROUP BY TAPE.APE_ENTIDAD_UMO, TAPE.APE_CENTRO_UMO,
         TC.TCCENTIT, TC.TCCOFICI, TC.TCMOFICI
ORDER BY FILAS DESC;