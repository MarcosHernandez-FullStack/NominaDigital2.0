SELECT TBCREATOR,
       TBNAME,
       COLNO,
       NAME,
       COLTYPE,
       LENGTH,
       SCALE,
       NULLS
FROM SYSIBM.SYSCOLUMNS
WHERE TBNAME = 'BGDTAPE'
  AND NAME IN ('APE_FECHA_FORMAL', 'APE_FECHA_APE', 'APE_ENTIDAD',
               'APE_CENTRO_ALTA', 'APE_DIGICCC1', 'APE_DIGICCC2',
               'APE_CUENTA', 'APE_DIVISA', 'APE_CONCEPTO',
               'APE_CENTRO_UMO', 'APE_USERID_UMO', 'APE_NETNAME_UMO',
               'APE_TIMEST_UMO', 'APE_ENTIDAD_UMO')
ORDER BY TBCREATOR, COLNO;