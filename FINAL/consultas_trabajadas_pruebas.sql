--CONSULTA PARA CONOCER DIFERENTE CASUISTICAS DE CANAL_DESC
SELECT
      TAPE.APE_FECHA_FORMAL AS FECHA_FORMAL,
      COUNT(*) AS TOTAL_REGISTROS,
      SUM(CASE WHEN TAPE.APE_USERID_UMO = 'BG7CAPEU' THEN 1 ELSE 0 END) AS NOMINA_DIGITAL_2_0,
      SUM(CASE WHEN TAPE.APE_USERID_UMO = 'ZG13003' THEN 1 ELSE 0 END) AS NOMINA_DIGITAL_1_0,
      SUM(CASE WHEN TAPE.APE_USERID_UMO NOT IN ('BG7CAPEU', 'ZG13003') OR TAPE.APE_USERID_UMO IS NULL THEN 1 ELSE 0 END) AS RED_OFICINAS
FROM GPBC.BGDTAPE TAPE
WHERE TAPE.APE_PRODUCTO = '02'
  AND TAPE.APE_SUBPRODU IN ('0046', '0047')
  -- AND TAPE.APE_IND_SITU = 'F'
  -- AND TAPE.APE_FECHA_FORMAL BETWEEN '2026-07-01' AND '2026-09-30'
GROUP BY TAPE.APE_FECHA_FORMAL
HAVING COUNT(DISTINCT 
         CASE
              WHEN TAPE.APE_USERID_UMO = 'BG7CAPEU' THEN 'NOMINA DIGITAL 2.0'
              WHEN TAPE.APE_USERID_UMO = 'ZG13003'  THEN 'NOMINA DIGITAL 1.0'
              ELSE 'RED DE OFICINAS'
         END
       ) = 3
ORDER BY TAPE.APE_FECHA_FORMAL DESC
