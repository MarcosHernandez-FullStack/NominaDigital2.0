-- CAMPOS DE UNION BGDTAPE - TCDT052 (ENTIDAD + OFICINA), IGUAL QUE BGJPNDG5
-- ENTIDAD_UMO / CENTRO_UMO : LADO BGDTAPE (CHAR 4)
-- TCCENTIT / TCCOFICI      : LADO TCDT052 (DECIMAL 4,0), TAL CUAL
-- *_TXT                    : LOS MISMOS A 4 DIGITOS, COMO SE COMPARAN
SELECT
      TAPE.APE_ENTIDAD_UMO,
      TAPE.APE_CENTRO_UMO,
      TCDT.TCCENTIT,
      TCDT.TCCOFICI,
      RIGHT(DIGITS(TCDT.TCCENTIT), 4),
      RIGHT(DIGITS(TCDT.TCCOFICI), 4),
      
      TAPE.APE_ENTIDAD_UMO,
      TAPE.APE_CENTRO_UMO,
      TCDT.TCCENTIT,
      TCDT.TCCOFICI,
      RIGHT(DIGITS(TCDT.TCCENTIT), 4) AS TCCENTIT_TXT,
      RIGHT(DIGITS(TCDT.TCCOFICI), 4) AS TCCOFICI_TXT,
      TAPE.APE_FECHA_FORMAL AS FECHA_FORMAL,
      TAPE.APE_FECHA_APE AS FECHA_APE,
      TAPE.APE_ENTIDAD CONCAT TAPE.APE_CENTRO_ALTA
      CONCAT TAPE.APE_DIGICCC1 CONCAT TAPE.APE_DIGICCC2
      CONCAT TAPE.APE_CUENTA AS NRO_CUENTA,
      TAPE.APE_DIVISA AS DIVISA,
      TAPE.APE_CONCEPTO AS CONCEPTO,
      TAPE.APE_ENTIDAD_UMO AS ENTIDAD_UMO,
      TAPE.APE_CENTRO_UMO AS CENTRO_UMO,
      
      TCDT.TCMOFICI AS NOMBRE_OFICINA,
      TAPE.APE_USERID_UMO AS USERID_UMO,
      TAPE.APE_NETNAME_UMO AS NETNAME_UMO,
      CASE
           WHEN TAPE.APE_USERID_UMO = 'BG7CAPEU'
                THEN 'NOMINA DIGITAL 2.0'
           WHEN TAPE.APE_USERID_UMO = 'ZG13003'
                THEN 'NOMINA DIGITAL 1.0'
           ELSE 'RED DE OFICINAS'
      END AS CANAL_DESC,
      VARCHAR_FORMAT(TAPE.APE_TIMEST_UMO, 'YYYY-MM-DD HH24:MI:SS')
                                                          AS TIMEST
     FROM GPBT.BGDTAPE TAPE
     LEFT JOIN GPBT.TCDT052 TCDT
            ON TAPE.APE_ENTIDAD_UMO = RIGHT(DIGITS(TCDT.TCCENTIT), 4)
           AND TAPE.APE_CENTRO_UMO  = RIGHT(DIGITS(TCDT.TCCOFICI), 4)
     WHERE TAPE.APE_PRODUCTO = '02'
     AND TAPE.APE_SUBPRODU IN ('0046', '0047')
     AND TAPE.APE_IND_SITU='F'
--   AND TAPE.APE_FECHA_FORMAL = DATE(TO_DATE('%%$ODATE', 'YYYYMMDD'))
     ORDER BY TAPE.APE_FECHA_FORMAL, TAPE.APE_FECHA_APE,
              NRO_CUENTA, TIMEST;

