SELECT
 TAPE.APE_FECHA_FORMAL,
 TAPE.APE_FECHA_APE,
 TAPE.APE_ENTIDAD || TAPE.APE_CENTRO_ALTA
 || TAPE.APE_DIGICCC1 || TAPE.APE_DIGICCC2
 || TAPE.APE_CUENTA AS NRO_CUENTA,
 TAPE.APE_DIVISA,
 TAPE.APE_CONCEPTO,
 TCDT.TCMOFCUR AS NOMBRE_OFICINA,
 TAPE.APE_USERID_UMO,
 TAPE.APE_NETNAME_UMO,
 CASE
      WHEN TAPE.APE_USERID_UMO = 'BG7CAPEU' THEN 'NOMINA DIGITAL 2.0'
      WHEN TAPE.APE_USERID_UMO = 'ZG13003' THEN 'NOMINA DIGITAL 1.0'
      ELSE 'RED DE OFICINAS'
 END AS APE_CANAL_DESC,
 VARCHAR_FORMAT(APE_TIMEST_UMO, 'YYYY-MM-DD HH24:MI:SS') AS FORMAT_APE_TIMEST_UMO
FROM GPBC.BGDTAPE TAPE
LEFT JOIN GPBC.TCDT050 TCDT ON TAPE.APE_CENTRO_UMO=TCDT.TCCOFICI
WHERE TAPE.APE_PRODUCTO = '02'
AND TAPE.APE_SUBPRODU IN ('0046', '0047')
AND TAPE.APE_IND_SITU='F'
